import json
import re
import tempfile
import tomllib
from pathlib import Path


GENERATED_MARKER = "# Generated by mise run harness:codex:roles:generate.\n"
GENERATED_HEADER = GENERATED_MARKER + "# Edit .harness/config.toml or the listed instruction fragments and regenerate.\n"


def render_roles(project_root: Path) -> dict[str, str]:
    config_path = project_root / ".harness/config.toml"
    with config_path.open("rb") as config_file:
        settings = tomllib.load(config_file)

    section = settings.get("roles", {})
    if not isinstance(section, dict):
        raise ValueError("roles must be a table")

    roles = section.get("role", [])
    if not isinstance(roles, list):
        raise ValueError("roles.role must be an array of tables")

    rendered_roles = {}
    for index, role in enumerate(roles, start=1):
        label = f"roles.role entry {index}"
        if not isinstance(role, dict):
            raise ValueError(f"{label} must be a table")

        name = role.get("name")
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", name):
            raise ValueError(
                f"{label} name must start with a letter or digit and contain only letters, digits, _ or -"
            )
        filename = f"{name}.toml"
        if filename in rendered_roles:
            raise ValueError(f"Duplicate Codex role name: {name}")

        description = role.get("description")
        if not isinstance(description, str) or not description.strip():
            raise ValueError(f"{label} ({name}) must have a non-empty description")

        fragments = role.get("fragments")
        if not isinstance(fragments, list) or not all(isinstance(path, str) and path.strip() for path in fragments):
            raise ValueError(f"{label} ({name}) fragments must be an array of file paths")

        instructions = "\n\n".join(
            (project_root / path).read_text(encoding="utf-8").strip("\n") for path in fragments
        )
        values = {"name": name, "description": description, "developer_instructions": instructions}
        lines = [f"{key} = {json.dumps(value, ensure_ascii=False)}\n" for key, value in values.items()]
        content = GENERATED_HEADER + "".join(lines).replace("\x7f", "\\u007f")
        tomllib.loads(content)
        rendered_roles[filename] = content

    return rendered_roles


def generate_roles(project_root: Path) -> None:
    rendered_roles = render_roles(project_root)
    agents_dir = project_root / ".codex/agents"
    marker = GENERATED_MARKER.encode("utf-8")
    generated_roles = {}
    for path in agents_dir.glob("*.toml"):
        if path.is_symlink() or not path.is_file():
            continue
        content = path.read_bytes()
        if content.startswith(marker):
            generated_roles[path.name] = content

    for filename in sorted(rendered_roles.keys() - generated_roles.keys()):
        destination = agents_dir / filename
        if destination.exists() or destination.is_symlink():
            raise ValueError(f"Refusing to overwrite a role file without the generation header: {destination}")

    if rendered_roles:
        agents_dir.mkdir(parents=True, exist_ok=True)
    for filename, content in rendered_roles.items():
        encoded = content.encode("utf-8")
        if generated_roles.get(filename) == encoded:
            continue
        with tempfile.NamedTemporaryFile(dir=agents_dir, suffix=".tmp", delete=False) as output:
            temporary = Path(output.name)
            try:
                output.write(encoded)
                output.close()
                temporary.replace(agents_dir / filename)
            finally:
                temporary.unlink(missing_ok=True)

    for filename in sorted(generated_roles.keys() - rendered_roles.keys()):
        (agents_dir / filename).unlink()

    print(f"Generated {len(rendered_roles)} Codex roles")


if __name__ == "__main__":
    try:
        generate_roles(Path.cwd())
    except (OSError, ValueError) as error:
        raise SystemExit(f"Could not generate Codex roles: {error}") from error
